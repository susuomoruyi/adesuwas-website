(function () {
  const S = window.SITE;
  const $ = (id) => document.getElementById(id);

  function el(tag, props, children) {
    const node = document.createElement(tag);
    Object.entries(props || {}).forEach(([k, v]) => {
      if (k === "class") node.className = v;
      else if (k === "text") node.textContent = v;
      else node.setAttribute(k, v);
    });
    (children || []).forEach((c) => c && node.appendChild(c));
    return node;
  }

  // An <img> that falls back to a labelled placeholder if the file is missing.
  function photo(img, label) {
    const holder = el("div", { class: "ph", "aria-hidden": "true" }, [
      el("span", { text: label || "Photo" }),
    ]);
    const image = el("img", { src: img.src, alt: img.alt || "", loading: "lazy" });
    image.addEventListener("error", () => image.remove());
    return [holder, image];
  }

  function formatDate(iso) {
    const d = new Date(iso + "T00:00:00");
    return d.toLocaleDateString("en-US", { year: "numeric", month: "short", day: "numeric" });
  }

  function stars(n) {
    return "★".repeat(n) + "☆".repeat(5 - n);
  }

  // Header / hero
  $("brand").textContent = S.name;
  $("hero-name").textContent = S.name + ".";
  $("hero-tagline").textContent = S.tagline;
  $("hero-intro").textContent = S.intro;
  $("footer-name").textContent = S.fullName;
  $("year").textContent = new Date().getFullYear();
  photo(S.portrait, "Portrait").forEach((n) => $("portrait").appendChild(n));

  S.gallery.forEach((g, i) => {
    const fig = el("figure", { class: "photo" }, photo(g, "Photo " + (i + 1)));
    $("gallery").appendChild(fig);
  });

  // About
  S.about.forEach((p) => $("about-body").appendChild(el("p", { text: p })));

  // Work: now
  const n = S.now;
  $("now").appendChild(el("p", { class: "dates", text: n.dates }));
  $("now").appendChild(el("h3", { text: n.role + " at " + n.company }));
  $("now").appendChild(el("p", { class: "summary", text: n.summary }));
  const ul = el("ul");
  n.highlights.forEach((h) => ul.appendChild(el("li", { text: h })));
  $("now").appendChild(ul);

  // Work: before
  if (!S.before.length) $("before-wrap").remove();
  S.before.forEach((b) => {
    $("before").appendChild(
      el("li", {}, [
        el("p", { class: "dates", text: b.dates }),
        el("h4", { text: b.role + ", " + b.company }),
        el("p", { text: b.summary }),
      ])
    );
  });

  // Books
  const COVER_COLORS = ["#c2410c", "#1f4d3a", "#2b3a67", "#7a2e4d", "#5b4b2e", "#34505f"];
  function bookCard(b, i) {
    const cover = el("div", { class: "cover photo" });
    if (b.cover) {
      photo({ src: b.cover, alt: "Cover of " + b.title }, "Cover").forEach((n) => cover.appendChild(n));
    } else {
      cover.classList.add("typo");
      cover.style.background = COVER_COLORS[i % COVER_COLORS.length];
      cover.appendChild(el("span", { class: "typo-title", text: b.title }));
      cover.appendChild(el("span", { class: "typo-author", text: b.author }));
    }
    const text = b.learned || b.note;
    const body = el("div", { class: "book-body" }, [
      el("h4", { text: b.title }),
      el("p", { class: "author", text: b.author }),
      b.rating ? el("p", { class: "rating", "aria-label": b.rating + " out of 5", text: stars(b.rating) }) : null,
      b.learned ? el("p", { class: "learned-label", text: "What I learned" }) : null,
      text ? el("p", { class: "note", text: text }) : null,
    ]);
    return el("article", { class: "book" }, [cover, body]);
  }
  if (S.reading.length) S.reading.forEach((b, i) => $("reading-now").appendChild(bookCard(b, i)));
  else $("reading-now-wrap").remove();
  S.read.forEach((b, i) => $("read").appendChild(bookCard(b, i)));
  $("read-count").textContent = "(" + S.read.length + ")";

  // Latest articles (from blog/posts.js, generated by `npm run build`)
  (window.POSTS || []).slice(0, 5).forEach((a) => {
    $("articles").appendChild(
      el("li", {}, [
        el("div", { class: "meta" }, [
          el("span", { text: formatDate(a.date) }),
          el("span", { class: "tag", text: a.minutes + " min read" }),
        ]),
        el("a", { href: "blog/" + a.slug + "/index.html", text: a.title }),
        a.description ? el("p", { text: a.description }) : null,
      ])
    );
  });

  // Contact
  $("email").href = "mailto:" + S.contact.email;
  $("email").textContent = S.contact.email;
  S.contact.links.forEach((l) => {
    $("links").appendChild(el("li", {}, [el("a", { href: l.url, text: l.label, rel: "noopener" })]));
  });
})();
